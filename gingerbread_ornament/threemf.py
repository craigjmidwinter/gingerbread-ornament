def _mat(s):
    v = [float(x) for x in s.split()]
    m = np.eye(4)
    m[:3, 0] = v[0:3]
    m[:3, 1] = v[3:6]
    m[:3, 2] = v[6:9]
    m[:3, 3] = v[9:12]
    return m


def _parse_meshes(xml_bytes):
    meshes = {}
    comps = {}
    root = ET.fromstring(xml_bytes)
    ns = {"m": NS_CORE}
    for obj in root.iter("{%s}object" % NS_CORE):
        oid = obj.get("id")
        mesh = obj.find("m:mesh", ns)
        if mesh is not None:
            vs = mesh.find("m:vertices", ns)
            ts = mesh.find("m:triangles", ns)
            v = np.array([[float(e.get("x")), float(e.get("y")), float(e.get("z"))] for e in vs], dtype=np.float64)
            t = np.array([[int(e.get("v1")), int(e.get("v2")), int(e.get("v3"))] for e in ts], dtype=np.int64)
            meshes[oid] = (v, t)
        c = obj.find("m:components", ns)
        if c is not None:
            comps[oid] = [(e.get("objectid"), e.get("{%s}path" % NS_PROD), _mat(e.get("transform", "1 0 0 0 1 0 0 0 1 0 0 0")))
                          for e in c]
    return root, meshes, comps


def read_3mf(path):
    """Return list of dict(name, verts, tris, extruder, colour) in world (bed) coordinates."""
    z = zipfile.ZipFile(path)
    names = z.namelist()
    root, meshes, comps = _parse_meshes(z.read("3D/3dmodel.model"))
    ext_meshes = {}
    for n in names:
        if n.startswith("3D/Objects/") and n.endswith(".model"):
            _, m, _ = _parse_meshes(z.read(n))
            ext_meshes["/" + n] = m
    extruders = {}
    part_names = {}
    if "Metadata/model_settings.config" in names:
        cfg = ET.fromstring(z.read("Metadata/model_settings.config"))
        for obj in cfg.iter("object"):
            for part in obj.iter("part"):
                pid = part.get("id")
                for md in part.iter("metadata"):
                    if md.get("key") == "extruder":
                        extruders[pid] = int(md.get("value"))
                    if md.get("key") == "name":
                        part_names[pid] = md.get("value")
    colours = []
    if "Metadata/project_settings.config" in names:
        import json
        try:
            colours = json.loads(z.read("Metadata/project_settings.config")).get("filament_colour", [])
        except Exception:
            colours = []
    out = []
    ns = {"m": NS_CORE}
    for item in root.iter("{%s}item" % NS_CORE):
        bt = _mat(item.get("transform", "1 0 0 0 1 0 0 0 1 0 0 0"))
        oid = item.get("objectid")
        if oid in comps:
            for cid, cpath, ct in comps[oid]:
                src = ext_meshes.get(cpath, meshes) if cpath else meshes
                if cid not in src:
                    continue
                v, t = src[cid]
                m = bt @ ct
                vw = v @ m[:3, :3].T + m[:3, 3]
                ex = extruders.get(cid, 1)
                col = colours[ex - 1] if ex - 1 < len(colours) else None
                out.append(dict(name=part_names.get(cid, "part%s" % cid), verts=vw, tris=t, extruder=ex, colour=col))
        elif oid in meshes:
            v, t = meshes[oid]
            vw = v @ bt[:3, :3].T + bt[:3, 3]
            out.append(dict(name="object%s" % oid, verts=vw, tris=t, extruder=1, colour=None))
    return out
